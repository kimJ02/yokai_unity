namespace YokaiFront.Core
{
    /// <summary>
    /// 정식 아트 전까지 쓰는 임시 도형 — 사용자 지시(2026-09-16)
    /// **"캐릭터나 몬스터에 일단 스킨 씌우지 말고 네모 세모 동그라미로만."**
    ///
    /// ## 도형 배정 기준: "다르게 대응해야 하는 것끼리 갈랐다"
    /// 도형을 종류마다 아무렇게나 주면 색만 다른 도형 더미가 된다. 대신 **플레이어가 취해야 하는
    /// 행동**을 기준으로 세 갈래로 나눴다.
    ///
    /// | 도형 | 무엇 | 왜 |
    /// |---|---|---|
    /// | <see cref="Square"/> 네모 | **플레이어** 4종, **성소** | 각져 있어 둥근 몹 무리 속에서 즉시 눈에 띈다. 성소는 안 움직이는 구조물이라 같은 "각진" 부류로 묶었다(세로로 길고 색이 달라 헷갈리지 않는다) |
    /// | <see cref="Circle"/> 동그라미 | **근접 추적 몹**(오니·대오니·분열귀·새끼), 경험치 구슬 | 가장 수가 많다. "그냥 달려오는 것" = 거리만 관리하면 되는 부류 |
    /// | <see cref="Triangle"/> 세모 | **방향성 위협**(도깨비불 비행·사수귀 사격·돌진귀 돌진), **보스** | 뾰족한 쪽이 위협이 오는 방향을 읽게 한다. 이 셋은 거리 관리로 안 되고 **예고 동작을 보고 피해야** 한다 |
    ///
    /// 그래서 화면에서 **세모가 보이면 "피할 준비"**, 동그라미는 "밀어내기", 네모는 "나 또는 목표물"로
    /// 읽힌다. 색은 종류 구분(원본 `colors.soul`)에 그대로 쓴다.
    ///
    /// 실제 파일은 `Assets/Editor/BuildPrimitiveSprites`가 굽고(`Assets/Sprites/Primitive/`),
    /// 씬 빌더가 각 컴포넌트에 주입한다.
    /// </summary>
    public enum PrimitiveShape
    {
        Circle,
        Square,
        Triangle,
    }
}
